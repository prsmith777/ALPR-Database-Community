import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
export const migrationHash = sql => createHash("sha256").update(sql.replace(/\r\n/g, "\n")).digest("hex");

export async function compileMigrations(directory = path.join(root, "migrations")) {
  const files = (await readdir(directory)).filter(name => /^\d{4}_[a-z0-9_]+\.sql$/.test(name)).sort();
  if (!files.length) throw new Error("No migration sources found");
  const seen = new Set();
  const units = [];
  for (const file of files) {
    const sql = (await readFile(path.join(directory, file), "utf8")).replace(/\r\n/g, "\n");
    const version = sql.match(/^-- migration: ([a-z0-9_]+)$/m)?.[1];
    if (!version || seen.has(version)) throw new Error("Missing or duplicate migration version: " + file);
    seen.add(version);
    const hash = migrationHash(sql);
    const quoted = "$source_" + hash.slice(0, 16) + "$";
    if (sql.includes(quoted)) throw new Error("Migration delimiter collision");
    units.push({ file, version, hash, sql, quoted });
  }
  const prelude = `-- GENERATED by node scripts/build-migrations.mjs. Edit only new migration sources.
-- The single-file, pure-SQL entry point also supports older Windows updaters,
-- Docker's psql runner, and logical imports. Callers must use one transaction.
SELECT pg_advisory_xact_lock(6839271042261);
CREATE TABLE IF NOT EXISTS public.schema_migrations (
  version VARCHAR(100) PRIMARY KEY,
  description TEXT NOT NULL,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE public.schema_migrations ADD COLUMN IF NOT EXISTS sql_sha256 CHAR(64);
-- Legacy markers were committed by the previous transactional SQL runner.
-- Validate its identity authority before adopting markers as the baseline.
DO $baseline$
BEGIN
  IF EXISTS (SELECT 1 FROM public.schema_migrations WHERE version = '2026092701_native_reid') THEN
    IF to_regclass('public.vehicle_reid_control') IS NULL
       OR to_regclass('public.vehicle_direction_observations') IS NULL THEN
      RAISE EXCEPTION 'Legacy migration baseline is incomplete';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.vehicle_reid_control WHERE singleton AND mode = 'v2_primary') THEN
      RAISE EXCEPTION 'Legacy identity authority does not match its migration marker';
    END IF;
  END IF;
END;
$baseline$;
`;
  const body = units.map(unit => `
-- ${unit.file}
DO $migration$
DECLARE recorded_hash TEXT;
BEGIN
  SELECT sql_sha256 INTO recorded_hash FROM public.schema_migrations WHERE version = '${unit.version}';
  IF FOUND THEN
    IF recorded_hash IS NOT NULL AND recorded_hash <> '${unit.hash}' THEN
      RAISE EXCEPTION 'Applied migration checksum differs: ${unit.version}';
    END IF;
    IF recorded_hash IS NULL THEN
      UPDATE public.schema_migrations SET sql_sha256 = '${unit.hash}' WHERE version = '${unit.version}';
    END IF;
  ELSE
    EXECUTE ${unit.quoted}${unit.sql}${unit.quoted};
    IF NOT EXISTS (SELECT 1 FROM public.schema_migrations WHERE version = '${unit.version}') THEN
      RAISE EXCEPTION 'Migration did not record completion: ${unit.version}';
    END IF;
    UPDATE public.schema_migrations SET sql_sha256 = '${unit.hash}' WHERE version = '${unit.version}';
  END IF;
END;
$migration$;
`).join("");
  return { sql: prelude + body, manifest: units.map(({ file, version, hash }) => ({ file, version, sha256: hash })) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { sql, manifest } = await compileMigrations();
  if (process.argv.includes("--check")) {
    if ((await readFile(path.join(root, "migrations.sql"), "utf8")).replace(/\r\n/g, "\n") !== sql)
      throw new Error("migrations.sql is stale; run node scripts/build-migrations.mjs");
  } else {
    await writeFile(path.join(root, "migrations.sql"), sql);
  }
  console.log(`Verified ${manifest.length} ordered, checksummed migrations`);
}
